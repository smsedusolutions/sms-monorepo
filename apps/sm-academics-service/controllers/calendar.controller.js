const { getSchoolDbConnection } = require('../configs/db');
const { getSchoolDbName } = require('../utils/schoolDbHelper');
const { CalendarEventSchema, PTMSchema, ExamSchema, ExamScheduleSchema } = require('@sms/shared/models');

const getModels = (schoolDbName) => {
    const conn = getSchoolDbConnection(schoolDbName);
    return {
        CalendarEvent: conn.models.CalendarEvent || conn.model('CalendarEvent', CalendarEventSchema),
        PTM: conn.models.PTM || conn.model('PTM', PTMSchema),
        Exam: conn.models.Exam || conn.model('Exam', ExamSchema),
        ExamSchedule: conn.models.ExamSchedule || conn.model('ExamSchedule', ExamScheduleSchema),
    };
};

// ==========================================
// 1. GET CALENDAR EVENTS (Aggregates Custom Events + PTM + Exams with Role Visibility)
// GET /api/academics/school/:schoolId/calendar
// ==========================================
const getCalendarEvents = async (req, res) => {
    try {
        const { schoolId } = req.params;
        const { from, to, eventType, audience, search } = req.query;
        const userRole = req.user?.role || '';

        const dbName = await getSchoolDbName(schoolId);
        const { CalendarEvent, PTM, Exam } = getModels(dbName);

        const filter = { schoolId };

        // 1. Event Type filtering
        if (eventType && eventType !== 'all') {
            filter.eventType = eventType;
        }

        // 2. Audience / Role-based visibility filtering
        const isStaffOrAdmin = ['sch_admin', 'principal', 'super_admin'].includes(userRole);
        if (!isStaffOrAdmin && userRole) {
            if (userRole === 'teacher') {
                filter.targetAudience = { $in: ['all', 'teacher', 'staff'] };
            } else if (userRole === 'student') {
                filter.targetAudience = { $in: ['all', 'student'] };
            } else if (userRole === 'parent') {
                filter.targetAudience = { $in: ['all', 'parent'] };
            }
        } else if (audience && audience !== 'all') {
            // Admin explicitly filtering by target audience
            filter.targetAudience = { $in: [audience, 'all'] };
        }

        // 3. Search query
        if (search && search.trim()) {
            const regex = new RegExp(search.trim(), 'i');
            filter.$or = [
                { title: regex },
                { description: regex },
                { venue: regex }
            ];
        }

        // 4. Date range filter
        if (from && to) {
            const fromDate = new Date(from);
            fromDate.setUTCHours(0, 0, 0, 0);
            const toDate = new Date(to);
            toDate.setUTCHours(23, 59, 59, 999);

            const dateCondition = [
                { startDate: { $gte: fromDate, $lte: toDate } },
                { endDate: { $gte: fromDate, $lte: toDate } },
                { startDate: { $lte: fromDate }, endDate: { $gte: toDate } },
            ];

            if (filter.$or) {
                filter.$and = [
                    { $or: filter.$or },
                    { $or: dateCondition }
                ];
                delete filter.$or;
            } else {
                filter.$or = dateCondition;
            }
        }

        // Fetch custom events
        const customEvents = await CalendarEvent.find(filter).sort({ startDate: 1 }).lean();

        // 2. Fetch PTM sessions (only if allowed for role & matching eventType filter)
        let ptmEvents = [];
        const isPTMVisible = isStaffOrAdmin || ['teacher', 'parent'].includes(userRole);
        if (isPTMVisible && (!eventType || eventType === 'all' || eventType === 'ptm' || eventType === 'parent_meeting')) {
            const ptmFilter = { schoolId };
            if (from && to) {
                const fromDate = new Date(from);
                fromDate.setUTCHours(0, 0, 0, 0);
                const toDate = new Date(to);
                toDate.setUTCHours(23, 59, 59, 999);
                ptmFilter.date = { $gte: fromDate, $lte: toDate };
            }
            if (search && search.trim()) {
                const searchRegex = new RegExp(search.trim(), 'i');
                ptmFilter.$or = [
                    { title: searchRegex },
                    { description: searchRegex },
                    { venue: searchRegex }
                ];
            }

            const ptms = await PTM.find(ptmFilter).sort({ date: 1 }).lean();
            ptmEvents = ptms.map(p => ({
                _id: p._id.toString(),
                schoolId: p.schoolId,
                title: `PTM: ${p.title}`,
                description: `${p.startTime || ''} - ${p.endTime || ''}${p.venue ? ` | Venue: ${p.venue}` : ''}${p.className ? ` | ${p.className}` : ''}`,
                eventType: 'parent_meeting',
                startDate: p.date,
                endDate: p.date,
                venue: p.venue || null,
                targetAudience: ['parent', 'teacher'],
                isAutoGenerated: true,
                sourceId: p._id,
            }));
        }

        // 3. Fetch Exams (if eventType is not set or matches 'exam')
        let examEvents = [];
        if (!eventType || eventType === 'all' || eventType === 'exam') {
            const examFilter = { schoolId, status: { $ne: 'draft' } };
            if (from && to) {
                examFilter.$or = [
                    { startDate: { $gte: new Date(from), $lte: new Date(to) } },
                    { endDate: { $gte: new Date(from), $lte: new Date(to) } },
                    { startDate: { $lte: new Date(from) }, endDate: { $gte: new Date(to) } },
                ];
            }
            if (search && search.trim()) {
                const searchRegex = new RegExp(search.trim(), 'i');
                examFilter.$or = [
                    { name: searchRegex },
                    { academicYear: searchRegex }
                ];
            }

            const exams = await Exam.find(examFilter).sort({ startDate: 1 }).lean();
            examEvents = exams.map(e => ({
                _id: e._id.toString(),
                schoolId: e.schoolId,
                title: `Exam: ${e.name}`,
                description: `Academic Year: ${e.academicYear} | Status: ${e.status}`,
                eventType: 'exam',
                startDate: e.startDate,
                endDate: e.endDate,
                venue: null,
                targetAudience: ['all'],
                isAutoGenerated: true,
                sourceId: e.examId || e._id,
            }));
        }

        // Combine and sort chronologically
        const allEvents = [...customEvents, ...ptmEvents, ...examEvents].sort(
            (a, b) => new Date(a.startDate).getTime() - new Date(b.startDate).getTime()
        );

        res.status(200).json({ success: true, data: allEvents, count: allEvents.length });
    } catch (error) {
        console.error('Get Calendar Events Error:', error);
        res.status(500).json({ success: false, message: error.message });
    }
};

// ==========================================
// 2. CREATE CALENDAR EVENT
// POST /api/academics/school/:schoolId/calendar
// ==========================================
const createCalendarEvent = async (req, res) => {
    try {
        const { schoolId } = req.params;
        const { title, description, eventType, startDate, endDate, targetAudience, venue } = req.body;

        if (!title || !startDate) {
            return res.status(400).json({ success: false, message: 'Title and Start Date are required' });
        }

        const dbName = await getSchoolDbName(schoolId);
        const { CalendarEvent } = getModels(dbName);

        const audience = Array.isArray(targetAudience) && targetAudience.length > 0
            ? targetAudience
            : (targetAudience ? [targetAudience] : ['all']);

        const event = new CalendarEvent({
            schoolId,
            title,
            description: description || null,
            eventType: eventType || 'event',
            startDate: new Date(startDate),
            endDate: endDate ? new Date(endDate) : new Date(startDate),
            targetAudience: audience,
            venue: venue || null,
            createdBy: req.user?.userId || req.user?.adminId || null,
        });

        await event.save();
        res.status(201).json({ success: true, message: 'Event added to calendar', data: event });
    } catch (error) {
        console.error('Create Calendar Event Error:', error);
        res.status(500).json({ success: false, message: error.message });
    }
};

// ==========================================
// 3. UPDATE CALENDAR EVENT
// PUT /api/academics/school/:schoolId/calendar/:eventId
// ==========================================
const updateCalendarEvent = async (req, res) => {
    try {
        const { schoolId, eventId } = req.params;
        const { title, description, eventType, startDate, endDate, targetAudience, venue } = req.body;

        const dbName = await getSchoolDbName(schoolId);
        const { CalendarEvent } = getModels(dbName);

        const updateData = {};
        if (title !== undefined) updateData.title = title;
        if (description !== undefined) updateData.description = description;
        if (eventType !== undefined) updateData.eventType = eventType;
        if (startDate !== undefined) updateData.startDate = new Date(startDate);
        if (endDate !== undefined) updateData.endDate = endDate ? new Date(endDate) : new Date(startDate);
        if (venue !== undefined) updateData.venue = venue;
        if (targetAudience !== undefined) {
            updateData.targetAudience = Array.isArray(targetAudience) && targetAudience.length > 0
                ? targetAudience
                : [targetAudience];
        }

        const updated = await CalendarEvent.findOneAndUpdate(
            { schoolId, _id: eventId },
            { $set: updateData },
            { new: true }
        );

        if (!updated) {
            return res.status(404).json({ success: false, message: 'Event not found' });
        }

        res.status(200).json({ success: true, message: 'Event updated successfully', data: updated });
    } catch (error) {
        console.error('Update Calendar Event Error:', error);
        res.status(500).json({ success: false, message: error.message });
    }
};

// ==========================================
// 4. DELETE CALENDAR EVENT
// DELETE /api/academics/school/:schoolId/calendar/:eventId
// ==========================================
const deleteCalendarEvent = async (req, res) => {
    try {
        const { schoolId, eventId } = req.params;
        const dbName = await getSchoolDbName(schoolId);
        const { CalendarEvent } = getModels(dbName);

        const deleted = await CalendarEvent.findOneAndDelete({ schoolId, _id: eventId });
        if (!deleted) return res.status(404).json({ success: false, message: 'Event not found' });

        res.status(200).json({ success: true, message: 'Event deleted' });
    } catch (error) {
        console.error('Delete Calendar Event Error:', error);
        res.status(500).json({ success: false, message: error.message });
    }
};

module.exports = {
    getCalendarEvents,
    createCalendarEvent,
    updateCalendarEvent,
    deleteCalendarEvent,
};
